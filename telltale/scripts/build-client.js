'use strict';
/**
 * Bundles src/lexicons.js + src/detector.js into a browser script so the
 * analyze page can score text live while you type, using the exact same
 * engine as the server (no drift between the two).
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');

function build() {
  const lex = read('src/lexicons.js').replace(/\bmodule\.exports\s*=\s*\{[\s\S]*?\};\s*$/, '');
  const lexExport = read('src/lexicons.js').match(/module\.exports\s*=\s*\{([\s\S]*?)\};\s*$/);
  const lexNames = lexExport ? lexExport[1].split(',').map((s) => s.trim().split(':')[0].trim()).filter(Boolean) : [];
  const det = read('src/detector.js')
    .replace(/const LEX = require\('\.\/lexicons'\);/, 'const LEX = TellTaleLex;')
    .replace(/\bmodule\.exports\s*=\s*\{[\s\S]*?\};\s*$/m, '');

  const bundle = `/* TellTale engine — auto-generated by scripts/build-client.js. Do not edit. */
(function () {
  'use strict';
  var modules = {};
  function define(name, fn) { var m = { exports: {} }; fn(m, m.exports); modules[name] = m.exports; }
  var requireShim = function (name) {
    if (name === './lexicons') return modules.lexicons;
    throw new Error('Unknown module: ' + name);
  };

  define('lexicons', function (module, exports) {
${lex}
    module.exports = { ${lexNames.join(', ')} };
  });

  define('detector', function (module, exports) {
    var require = requireShim;
    var TellTaleLex = modules.lexicons;
${det}
    module.exports = { analyze: analyze, normalizeText: normalizeText, segment: segment, SIGNAL_DEFS: SIGNAL_DEFS };
  });

  window.TellTale = modules.detector;
  window.TellTaleLexicons = modules.lexicons;
})();
`;
  const outDir = path.join(root, 'public', 'assets');
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, 'telltale-engine.js'), bundle);
  return Buffer.byteLength(bundle);
}

if (require.main === module) {
  const bytes = build();
  process.stdout.write(`built public/assets/telltale-engine.js (${(bytes / 1024).toFixed(1)} kB)\n`);
}

module.exports = { build };
